"use strict";
const { contextBridge, ipcRenderer, webFrame } = require("electron");
const inv = (ch, ...a) => ipcRenderer.invoke(ch, ...a);
contextBridge.exposeInMainWorld("api", {
  load: () => inv("data:load"),
  saveNote: (n) => inv("note:save", n),
  deleteNote: (id) => inv("note:delete", id),
  saveNotebooks: (l) => inv("notebooks:save", l),
  saveSession: (s) => inv("session:save", s),
  savePrefs: (p) => inv("prefs:save", p),
  saveImage: (d) => inv("image:save", d),
  chooseFolder: () => inv("folder:choose"),
  openFolder: (w) => inv("folder:open", w),
  openLink: (u) => inv("link:open", u),
  setFullscreen: (on) => inv("win:fullscreen", on),
  focus: () => inv("win:focus"),
  reload: () => inv("win:reload"),
  exportNote: (o) => inv("note:export", o),
  flush: (payload) => ipcRenderer.sendSync("flush", payload),
  onFullscreen: (cb) => ipcRenderer.on("win:fullscreen", (e, v) => cb(v)),
  saveAudio: (buf, ext) => inv("audio:save", buf, ext),
  voiceStatus: () => inv("whisper:status"),
  voiceDownload: () => inv("whisper:download"),
  transcribe: (wav, lang) => inv("whisper:transcribe", wav, lang),
  voiceRemove: () => inv("whisper:remove"),
  onVoiceProgress: (cb) => ipcRenderer.on("whisper:progress", (e, v) => cb(v)),
  grammar: (text, lang) => inv("grammar:check", text, lang),
  misspelled: (w) => { try { return webFrame.isWordMisspelled(w); } catch (e) { return false; } },
  suggest: (w) => { try { return webFrame.getWordSuggestions(w); } catch (e) { return []; } },
  onProof: (cb) => ipcRenderer.on("ctx:proof", (e, v) => cb(v)),
  quickInfo: () => inv("quick:info"),
  quickDraft: (t) => inv("quick:draft", t),
  quickAudios: (l) => inv("quick:audios", l),
  quickSetNb: (id) => inv("quick:setnb", id),
  quickPin: (on) => inv("quick:pin", on),
  quickClose: () => inv("quick:close"),
  quickConvert: (o) => inv("quick:convert", o),
  quickOpenApp: (id) => inv("quick:openapp", id),
  setLogin: (on) => inv("login:set", on),
  cleanAttachments: (keep, minAge) => inv("attachments:cleanup", keep, minAge),
  backupList: () => inv("backup:list"),
  restoreNote: (id) => inv("backup:restoreNote", id),
  restoreDay: (d) => inv("backup:restoreDay", d),
  enexPick: () => inv("enex:pick"),
  openAttachment: (n) => inv("attach:open", n),
  onQuick: (ev, cb) => ipcRenderer.on("quick:" + ev, (e, v) => cb(v)),
  quickAdded: (r) => ipcRenderer.send("quick:added", r),
  checkUpdate: () => inv("update:check"),
  installUpdate: (info) => inv("update:install", info),
  onUpdateAvailable: (cb) => ipcRenderer.on("update:available", (e, v) => cb(v)),
  onUpdateProgress: (cb) => ipcRenderer.on("update:progress", (e, v) => cb(v)),
  imageData: (name) => inv("image:dataurl", name),
  appVersion: () => { try { return ipcRenderer.sendSync("app:version"); } catch (e) { return ""; } }
});
